// Índice central de todos los hechizos
export const ALL_SPELLS: Spell[] = [
    ...FIRE_SPELLS,
    ...EARTH_SPELLS,
    ...WATER_SPELLS,
    ...AIR_SPELLS,
    ...LIGHT_SPELLS,
    ...DARKNESS_SPELLS,
    ...ELECTRIC_SPELLS,
    ...VITAL_SPELLS,
    ...COMBO_SPELLS,
];

export function getSpellById(id: string): Spell | undefined {
    return ALL_SPELLS.find((s) => s.id === id);
}

export function getSpellsForElement(
    element: string,
    playerLevel: number,
): Spell[] {
    return ALL_SPELLS.filter(
        (s) =>
            s.element === element &&
            !s.isCombo &&
            s.requiredLevel <= playerLevel,
    );
}

export function getAvailableCombos(
    unlockedElements: string[],
    elementLevels: Record<string, number>,
): Spell[] {
    return COMBO_SPELLS.filter((spell) =>
        spell.comboElements!.every(
            (el) =>
                unlockedElements.includes(el) &&
                (elementLevels[el] ?? 0) >= spell.requiredLevel,
        ),
    );
}
